param(
    [string]$SourceRepo = 'E:\Desktop\game\mir2x',
    [string]$Compiler = 'E:\Desktop\game\toolchain\msys64\ucrt64\bin\g++.exe',
    [string]$CerealInclude = 'E:\Desktop\game\b_mir2x\build\vcpkg_installed\x64-mingw-static\include',
    [string]$OutputFile = ''
)

$ErrorActionPreference = 'Stop'
$repoRoot = Resolve-Path (Join-Path $PSScriptRoot '..\..')
if ([string]::IsNullOrWhiteSpace($OutputFile)) {
    $OutputFile = Join-Path $repoRoot 'internal/protocol/testdata/serdes-golden.json'
}
$SourceRepo = (Resolve-Path -LiteralPath $SourceRepo).Path
$Compiler = (Resolve-Path -LiteralPath $Compiler).Path
$CerealInclude = (Resolve-Path -LiteralPath $CerealInclude).Path
$probe = Join-Path $PSScriptRoot 'serdes_fixture_probe.cpp'
$utf8 = New-Object System.Text.UTF8Encoding($false)

$tempDir = Join-Path ([System.IO.Path]::GetTempPath()) ('mir2x-serdes-fixture-' + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $tempDir -Force | Out-Null
$exe = Join-Path $tempDir 'serdes_fixture_probe.exe'
$stdout = Join-Path $tempDir 'stdout.txt'
$stderr = Join-Path $tempDir 'stderr.txt'

$compilerDir = Split-Path -Parent $Compiler
$oldPath = $env:PATH
$env:PATH = "$compilerDir;$oldPath"
try {
    $process = Start-Process -FilePath $Compiler -ArgumentList @('-std=c++23', '-O0', '-I', $CerealInclude, $probe, '-o', $exe) -Wait -PassThru -NoNewWindow -RedirectStandardOutput $stdout -RedirectStandardError $stderr
    if ($process.ExitCode -ne 0) {
        $compilerError = if (Test-Path $stderr) { Get-Content $stderr -Raw } else { '' }
        throw "C++ serdes fixture probe failed with exit code $($process.ExitCode):`n$compilerError"
    }
    $rawOutput = (& $exe 2>&1 | Out-String).TrimEnd()
    if ($LASTEXITCODE -ne 0) {
        throw "C++ serdes fixture probe execution failed with exit code $LASTEXITCODE"
    }
}
finally {
    $env:PATH = $oldPath
    Remove-Item -LiteralPath $tempDir -Recurse -Force -ErrorAction SilentlyContinue
}

$fixtures = [ordered]@{}
foreach ($line in ($rawOutput -split "`r?`n")) {
    $parts = $line -split "`t"
    if ($parts.Count -ne 3) { throw "unexpected fixture line: $line" }
    $fixtures[$parts[0]] = [ordered]@{
        size = [int]$parts[1]
        hex = $parts[2]
    }
}

$commit = (& git -C $SourceRepo rev-parse HEAD).Trim()
$result = [ordered]@{
    generated_at_utc = [DateTime]::UtcNow.ToString('o')
    source_repo = $SourceRepo
    source_commit = $commit
    note = 'Generated by compiling tools/protocol-fixtures/serdes_fixture_probe.cpp with cereal PortableBinaryOutputArchive.'
    fixtures = $fixtures
}

$parent = Split-Path -Parent $OutputFile
if ($parent) { New-Item -ItemType Directory -Path $parent -Force | Out-Null }
[System.IO.File]::WriteAllText($OutputFile, ($result | ConvertTo-Json -Depth 8) + "`n", $utf8)
Write-Host "Wrote $($fixtures.Count) serdes fixtures to $OutputFile"
