param(
    [string]$Compiler = 'E:\Desktop\game\toolchain\msys64\ucrt64\bin\g++.exe',
    [string]$OutputFile = ''
)

$ErrorActionPreference = 'Stop'
$repoRoot = Resolve-Path (Join-Path $PSScriptRoot '..\..')
if ([string]::IsNullOrWhiteSpace($OutputFile)) {
    $OutputFile = Join-Path $repoRoot 'internal/protocol/testdata/framing-golden.json'
}
$Compiler = (Resolve-Path -LiteralPath $Compiler).Path
$probe = Join-Path $PSScriptRoot 'framing_fixture_probe.cpp'
$utf8 = New-Object System.Text.UTF8Encoding($false)

$tempDir = Join-Path ([System.IO.Path]::GetTempPath()) ('mir2x-framing-fixture-' + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $tempDir -Force | Out-Null
$exe = Join-Path $tempDir 'framing_fixture_probe.exe'
$stdout = Join-Path $tempDir 'stdout.txt'
$stderr = Join-Path $tempDir 'stderr.txt'

$compilerDir = Split-Path -Parent $Compiler
$oldPath = $env:PATH
$env:PATH = "$compilerDir;$oldPath"
try {
    $process = Start-Process -FilePath $Compiler -ArgumentList @('-std=c++23', '-O0', $probe, '-o', $exe) -Wait -PassThru -NoNewWindow -RedirectStandardOutput $stdout -RedirectStandardError $stderr
    if ($process.ExitCode -ne 0) {
        $compilerError = if (Test-Path $stderr) { Get-Content $stderr -Raw } else { '' }
        throw "C++ framing fixture probe failed with exit code $($process.ExitCode):`n$compilerError"
    }
    $rawOutput = (& $exe 2>&1 | Out-String).TrimEnd()
    if ($LASTEXITCODE -ne 0) {
        throw "C++ framing fixture probe execution failed with exit code $LASTEXITCODE"
    }
}
finally {
    $env:PATH = $oldPath
    Remove-Item -LiteralPath $tempDir -Recurse -Force -ErrorAction SilentlyContinue
}

$fixtures = [ordered]@{}
foreach ($line in ($rawOutput -split "`r?`n")) {
    $parts = $line -split "`t"
    if ($parts.Count -ne 8) { throw "unexpected framing fixture line: $line" }
    $fixtures[$parts[0]] = [ordered]@{
        direction = $parts[1]
        id = [int]$parts[2]
        kind = [int]$parts[3]
        data_len = [int]$parts[4]
        response_id = [uint64]$parts[5]
        payload_hex = $parts[6]
        packet_hex = $parts[7]
    }
}

$result = [ordered]@{
    generated_at_utc = [DateTime]::UtcNow.ToString('o')
    note = 'Generated by tools/protocol-fixtures/framing_fixture_probe.cpp, mirroring NetDriver::encodePostBuf and Channel parsing.'
    fixtures = $fixtures
}

$parent = Split-Path -Parent $OutputFile
if ($parent) { New-Item -ItemType Directory -Path $parent -Force | Out-Null }
$json = ($result | ConvertTo-Json -Depth 8) -replace "`r`n", "`n"
[System.IO.File]::WriteAllText($OutputFile, $json + "`n", $utf8)
Write-Host "Wrote $($fixtures.Count) framing fixtures to $OutputFile"
